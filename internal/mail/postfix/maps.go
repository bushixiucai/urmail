package postfix

import (
	"fmt"
	"sort"
	"strings"

	domainMail "github.com/bushixiucai/urmail/internal/domain/mail"
)

func renderVirtualMailboxMap(snap Snapshot) string {
	addresses := make([]string, 0, len(snap.Mailboxes))
	for _, m := range snap.Mailboxes {
		addresses = append(addresses, strings.ToLower(m.Address))
	}
	sort.Strings(addresses)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, addr := range addresses {
		fmt.Fprintf(&b, "%s 1\n", addr)
	}
	return b.String()
}

func renderVirtualAliasMap(snap Snapshot) string {
	type entry struct {
		key    string
		target string
	}
	entries := make([]entry, 0, len(snap.Aliases))
	for _, a := range snap.Aliases {
		domain := strings.ToLower(a.Domain)
		var key string
		if a.Kind == "catchall" {
			key = fmt.Sprintf("@%s", domain)
		} else {
			key = fmt.Sprintf("%s@%s", strings.ToLower(a.LocalPart), domain)
		}
		entries = append(entries, entry{
			key:    key,
			target: strings.ToLower(a.Target),
		})
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].key < entries[j].key
	})

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "%s  %s\n", e.key, e.target)
	}
	return b.String()
}

func renderArchiveBCCMap(snap Snapshot) string {
	mailboxes := append([]Mailbox(nil), snap.Mailboxes...)
	sort.Slice(mailboxes, func(i, j int) bool {
		return strings.ToLower(mailboxes[i].Address) < strings.ToLower(mailboxes[j].Address)
	})
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, mailbox := range mailboxes {
		address := strings.ToLower(mailbox.Address)
		fmt.Fprintf(&b, "%s %s\n", address, domainMail.EncodeArchiveRecipient(mailbox.TenantID, mailbox.ID, address))
	}
	return b.String()
}

func renderArchiveTransportMap() string {
	return "# Generated by urmaild. DO NOT EDIT.\narchive.invalid urmail-archive:\n"
}

func renderSenderLoginMap(snap Snapshot) string {
	entries := make(map[string][]string, len(snap.Mailboxes)+len(snap.Aliases))
	for _, m := range snap.Mailboxes {
		address := strings.ToLower(m.Address)
		entries[address] = []string{address}
	}
	for _, a := range snap.Aliases {
		if len(a.SenderLogins) == 0 {
			continue
		}
		unique := map[string]bool{}
		for _, login := range a.SenderLogins {
			unique[login] = true
		}
		logins := make([]string, 0, len(unique))
		for login := range unique {
			logins = append(logins, login)
		}
		sort.Strings(logins)
		entries[strings.ToLower(a.LocalPart+"@"+a.Domain)] = logins
	}
	addresses := make([]string, 0, len(entries))
	for address := range entries {
		addresses = append(addresses, address)
	}
	sort.Strings(addresses)
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, addr := range addresses {
		fmt.Fprintf(&b, "%s %s\n", addr, strings.Join(entries[addr], ","))
	}
	return b.String()
}
