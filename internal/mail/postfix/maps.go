package postfix

import (
	"fmt"
	"sort"
	"strings"
)

func renderVirtualMailboxMap(snap Snapshot) string {
	addresses := make([]string, 0, len(snap.Mailboxes))
	for _, m := range snap.Mailboxes {
		addresses = append(addresses, strings.ToLower(m.Address))
	}
	sort.Strings(addresses)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, addr := range addresses {
		b.WriteString(fmt.Sprintf("%s 1\n", addr))
	}
	return b.String()
}

func renderVirtualAliasMap(snap Snapshot) string {
	type entry struct {
		key    string
		target string
	}
	entries := make([]entry, 0, len(snap.Aliases))
	for _, a := range snap.Aliases {
		domain := strings.ToLower(a.Domain)
		var key string
		if a.Kind == "catchall" {
			key = fmt.Sprintf("@%s", domain)
		} else {
			key = fmt.Sprintf("%s@%s", strings.ToLower(a.LocalPart), domain)
		}
		entries = append(entries, entry{
			key:    key,
			target: strings.ToLower(a.Target),
		})
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].key < entries[j].key
	})

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, e := range entries {
		b.WriteString(fmt.Sprintf("%s  %s\n", e.key, e.target))
	}
	return b.String()
}

