package postfix

import (
	"strings"
	"testing"
)

func TestSenderLoginGrantsPreserveReceivingOnlyAliases(t *testing.T) {
	snap := Snapshot{
		Domains:   []Domain{{FQDN: "example.test", Status: "active"}},
		Mailboxes: []Mailbox{{Address: "owner@example.test", Status: "active"}},
		Aliases: []Alias{
			{Domain: "example.test", LocalPart: "manual", Target: "owner@example.test", Kind: "alias", SenderLogins: []string{"owner@example.test", "owner@example.test"}},
			{Domain: "example.test", LocalPart: "automatic", Target: "owner@example.test", Kind: "alias"},
		},
	}
	got := renderSenderLoginMap(snap)
	want := "# Generated by urmaild. DO NOT EDIT.\nmanual@example.test owner@example.test\nowner@example.test owner@example.test\n"
	if got != want {
		t.Fatalf("sender map: %q", got)
	}
	if !strings.Contains(renderVirtualAliasMap(snap), "automatic@example.test  owner@example.test") {
		t.Fatal("receiving-only alias disappeared")
	}
}

func TestSenderLoginGrantsFailClosed(t *testing.T) {
	node := NodeConfig{Hostname: "box.example.test", PrimaryDomain: "example.test", StorageRoot: "/var/mail", TLSCertFile: "/etc/ssl/mail.cert", TLSKeyFile: "/etc/ssl/mail.key"}
	snap := Snapshot{Domains: []Domain{{FQDN: "example.test", Status: "active"}}, Mailboxes: []Mailbox{{Address: "owner@example.test", Status: "active"}}, Aliases: []Alias{{Domain: "example.test", LocalPart: "manual", Target: "owner@example.test", Kind: "alias"}}}
	for _, bad := range []string{"other@example.test", "owner@example.test\nroot@other.test", "OWNER@example.test"} {
		snap.Aliases[0].SenderLogins = []string{bad}
		if _, err := Generate(node, snap); err == nil {
			t.Fatal("unsafe sender grant accepted")
		}
	}
	snap.Aliases[0].SenderLogins = []string{"owner@example.test"}
	if _, err := Generate(node, snap); err != nil {
		t.Fatal(err)
	}
	snap.Aliases[0].Kind = "catchall"
	snap.Aliases[0].LocalPart = ""
	if _, err := Generate(node, snap); err == nil {
		t.Fatal("catchall granted sending")
	}
}
