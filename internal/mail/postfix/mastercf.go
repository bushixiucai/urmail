package postfix

import (
	"strings"
)

// policySocket resolves the effective policy service socket path, shared by
// main.cf (check_policy_service) and master.cf (submission/smtps overrides).
func policySocket(node NodeConfig) string {
	if node.PolicySocket != "" {
		return node.PolicySocket
	}
	return "/run/urmail-policy/policy.sock"
}

// fromBindMilter is the MAIL-04 From-authorization milter. It is attached
// only to the authenticated submission services: inbound mail on port 25
// legitimately carries foreign From domains and must not depend on urmaild
// being reachable.
const fromBindMilter = "inet:127.0.0.1:12302"

// submissionMilters mirrors the main.cf DKIM milter chain for the current
// node variant and appends the MAIL-04 From-authorization milter, so the
// per-service override on submission/smtps keeps DKIM signing intact.
func submissionMilters(node NodeConfig) string {
	switch {
	case node.V80Preserve && node.PreserveExternalOpenDKIM:
		return "inet:127.0.0.1:8891, inet:127.0.0.1:8893, " + fromBindMilter
	case node.V80Preserve:
		return "inet:127.0.0.1:12301, inet:127.0.0.1:8893, " + fromBindMilter
	default:
		return "inet:127.0.0.1:12301, " + fromBindMilter
	}
}

// submissionMilterOverrides renders the shared per-service milter overrides
// for submission/smtps: the full milter chain and fail-closed behavior (an
// unavailable From-authorization milter must not wave spoofable mail through).
func submissionMilterOverrides(node NodeConfig) []string {
	return []string{
		"-o smtpd_milters=" + submissionMilters(node),
		"-o milter_default_action=tempfail",
	}
}

func renderMasterCF(node NodeConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	b.WriteString("# ==========================================================================\n")
	b.WriteString("# service type  private unpriv  chroot  wakeup  maxproc command + args\n")
	b.WriteString("#               (yes)   (yes)   (no)    (never) (100)\n")
	b.WriteString("# ==========================================================================\n")
	// MAIL-03: the MX listener never offers AUTH at all. Mailbox users submit
	// through submission (587) or smtps (465), both of which force TLS.
	b.WriteString("smtp      inet  n       -       n       -       -       smtpd\n")
	b.WriteString("  -o smtpd_sasl_auth_enable=no\n")
	b.WriteString("submission inet n       -       n       -       -       smtpd\n")
	b.WriteString("  -o syslog_name=postfix/submission\n")
	b.WriteString("  -o smtpd_tls_security_level=encrypt\n")
	b.WriteString("  -o smtpd_sasl_auth_enable=yes\n")
	b.WriteString("  -o smtpd_reject_unlisted_recipient=no\n")
	b.WriteString("  -o milter_macro_daemon_name=ORIGINATING\n")
	for _, line := range submissionMilterOverrides(node) {
		b.WriteString("  " + line + "\n")
	}
	if node.PolicyEnabled {
		b.WriteString("  -o smtpd_data_restrictions=check_policy_service,unix:" + policySocket(node) + "\n")
	}
	b.WriteString("smtps     inet  n       -       n       -       -       smtpd\n")
	b.WriteString("  -o syslog_name=postfix/smtps\n")
	b.WriteString("  -o smtpd_tls_wrappermode=yes\n")
	b.WriteString("  -o smtpd_sasl_auth_enable=yes\n")
	b.WriteString("  -o smtpd_reject_unlisted_recipient=no\n")
	b.WriteString("  -o milter_macro_daemon_name=ORIGINATING\n")
	for _, line := range submissionMilterOverrides(node) {
		b.WriteString("  " + line + "\n")
	}
	if node.PolicyEnabled {
		b.WriteString("  -o smtpd_data_restrictions=check_policy_service,unix:" + policySocket(node) + "\n")
	}
	b.WriteString("pickup    unix  n       -       y       60      1       pickup\n")
	b.WriteString("cleanup   unix  n       -       y       -       0       cleanup\n")
	b.WriteString("qmgr      unix  n       -       n       300     1       qmgr\n")
	b.WriteString("tlsmgr    unix  -       -       y       1000?   1       tlsmgr\n")
	b.WriteString("rewrite   unix  -       -       y       -       -       trivial-rewrite\n")
	b.WriteString("bounce    unix  -       -       y       -       0       bounce\n")
	b.WriteString("defer     unix  -       -       y       -       0       bounce\n")
	b.WriteString("trace     unix  -       -       y       -       0       bounce\n")
	b.WriteString("verify    unix  -       -       y       -       1       verify\n")
	b.WriteString("flush     unix  n       -       y       1000?   0       flush\n")
	b.WriteString("proxymap  unix  -       -       n       -       -       proxymap\n")
	b.WriteString("proxywrite unix -       -       n       -       1       proxymap\n")
	b.WriteString("smtp      unix  -       -       y       -       -       smtp\n")
	b.WriteString("relay     unix  -       -       y       -       -       smtp\n")
	b.WriteString("showq     unix  n       -       y       -       -       showq\n")
	b.WriteString("error     unix  -       -       y       -       -       error\n")
	b.WriteString("retry     unix  -       -       y       -       -       error\n")
	b.WriteString("discard   unix  -       -       y       -       -       discard\n")
	b.WriteString("local     unix  -       n       n       -       -       local\n")
	b.WriteString("virtual   unix  -       n       n       -       -       virtual\n")
	b.WriteString("lmtp      unix  -       -       y       -       -       lmtp\n")
	b.WriteString("anvil     unix  -       -       y       -       1       anvil\n")
	b.WriteString("scache    unix  -       -       y       -       1       scache\n")
	b.WriteString("postlog   unix-dgram n  -       n       -       1       postlogd\n")

	if node.ArchiveEnabled {
		b.WriteString("\n# UrMail Archive Transport\n")
		b.WriteString("urmail-archive unix -   n       n       -       4       pipe\n  flags=Rq user=mailinabox argv=/usr/lib/urmail/archive-pipe --env-file /etc/urmail/urmaild.env --recipient ${recipient}\n")
	}

	return b.String()
}
