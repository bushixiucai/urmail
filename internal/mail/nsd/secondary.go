package nsd

import (
	"fmt"
	"sort"
	"strings"
)

// BT is a backtick literal, so markdown fences can be embedded in
// double-quoted Go strings without raw-string nesting.
const BT = "`"

// SecondaryConfig describes one hidden-primary/secondary DNS node pair for
// zone redundancy (DNS-12/14: redundancy made operational, not implied).
// The primary renders provide-xfr; the secondary renders request-xfr with the
// same TSIG key name. The TSIG secret itself is NEVER rendered here: it is
// provisioned by hand per the AXFR credential runbook below so the shared
// secret never passes through the database or the config render pipeline.
type SecondaryConfig struct {
	// Hostname of the secondary node (RFC 1123).
	Hostname string
	// Address of the secondary as seen from the primary (notify target).
	Address string
	// PrimaryAddress is the hidden primary's IP as seen from the secondary.
	PrimaryAddress string
	// TSIGKeyName identifies the shared AXFR credential (e.g. "axfr-urmail").
	// Only the NAME is rendered; the secret stays in the operator-managed
	// TSIG key file.
	TSIGKeyName string
	// TSIGAlgorithm defaults to hmac-sha256 when empty.
	TSIGAlgorithm string
	// Zones to replicate (zone names). Empty means all rendered zones.
	Zones []string
}

// Rendered fragment file names installed by the apply layer under
// /etc/nsd/nsd.conf.d/ on the primary and the secondary node respectively.
const (
	FileSecondaryConf     = "secondary.conf"
	FileSecondaryPeerConf = "secondary-peer.conf"
)

func (s SecondaryConfig) algorithm() string {
	if s.TSIGAlgorithm == "" {
		return "hmac-sha256"
	}
	return s.TSIGAlgorithm
}

// RenderSecondaryConf renders the PRIMARY-side redundancy fragment: per-zone
// notify + provide-xfr to the secondary, bound to the TSIG key name. Pure.
func RenderSecondaryConf(_ NodeConfig, snap Snapshot, sec SecondaryConfig) (string, error) {
	if err := validateSecondary(sec); err != nil {
		return "", err
	}
	zones := secondaryZones(snap, sec)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "# Hidden-primary AXFR/notify to secondary %s (%s).\n", sec.Hostname, sec.Address)
	b.WriteString("# The TSIG SECRET is not in this file: see /etc/nsd/tsig.keys and\n")
	b.WriteString("# the AXFR credential runbook for provisioning and rotation.\n\n")
	for _, z := range zones {
		b.WriteString("zone:\n")
		fmt.Fprintf(&b, "  name: %q\n", z)
		fmt.Fprintf(&b, "  notify: %s %s\n", sec.Address, sec.TSIGKeyName)
		fmt.Fprintf(&b, "  provide-xfr: %s %s\n\n", sec.Address, sec.TSIGKeyName)
	}
	return b.String(), nil
}

// RenderSecondaryPeerConf renders the SECONDARY-node fragment: request-xfr
// from the hidden primary. Pure.
func RenderSecondaryPeerConf(_ NodeConfig, snap Snapshot, sec SecondaryConfig) (string, error) {
	if err := validateSecondary(sec); err != nil {
		return "", err
	}
	zones := secondaryZones(snap, sec)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "# Secondary %s: AXFR from hidden primary %s.\n", sec.Hostname, sec.PrimaryAddress)
	fmt.Fprintf(&b, "# Install the matching TSIG key (name %s) in the local key file;\n", sec.TSIGKeyName)
	b.WriteString("# the secret is never rendered by urmaild.\n\n")
	b.WriteString("server:\n")
	fmt.Fprintf(&b, "  identity: %q\n\n", sec.Hostname)
	for _, z := range zones {
		b.WriteString("zone:\n")
		fmt.Fprintf(&b, "  name: %q\n", z)
		fmt.Fprintf(&b, "  request-xfr: %s %s\n\n", sec.PrimaryAddress, sec.TSIGKeyName)
	}
	return b.String(), nil
}

// RenderAXFRCredRunbook renders the operator runbook section covering AXFR
// credential (TSIG) handling: generation, storage, rotation and audit. Pure.
func RenderAXFRCredRunbook(sec SecondaryConfig) string {
	var b strings.Builder
	b.WriteString("## AXFR credential handling (TSIG)\n\n")
	fmt.Fprintf(&b, "Zone transfers between the hidden primary and the secondary (%s) are\nauthenticated with a shared TSIG key named %s (algorithm %s).\n\n", sec.Hostname, sec.TSIGKeyName, sec.algorithm())
	b.WriteString("### Provisioning\n\n")
	b.WriteString("1. Generate the secret offline on the primary: `ddns-confgen -a hmac-sha256 -k " + sec.TSIGKeyName + " -q` (or `tsig-keygen`).\n")
	b.WriteString("2. Store the key block ONLY in /etc/nsd/tsig.keys on both nodes,\n   owner root:nsd, mode 0600. Never commit it, never store it in the\n   database, and never pass it through the render pipeline: urmaild\n   renders the key NAME only.\n")
	b.WriteString("3. Include it from both nsd.conf files: `include: /etc/nsd/tsig.keys`.\n")
	b.WriteString("4. Restrict every provide-xfr/request-xfr to the key name; never allow\n   unauthenticated AXFR by address alone.\n\n")
	b.WriteString("### Rotation\n\n")
	b.WriteString("1. Generate a successor key with a NEW name (e.g. " + sec.TSIGKeyName + "-2).\n")
	b.WriteString("2. Publish both keys on both nodes; switch the rendered notify/xfr\n   references to the new name.\n")
	b.WriteString("3. After one refresh+retry window, remove the old key from both key\n   files and reload nsd-control on each node.\n\n")
	b.WriteString("### Audit\n\n")
	b.WriteString("- Confirm mode 0600 and root:nsd ownership on /etc/nsd/tsig.keys.\n")
	b.WriteString("- Check nsd.log for AXFR denied events from unkeyed peers.\n")
	b.WriteString("- The secret must never appear in rendered output, config backups, or\n  this runbook output; rotate immediately if it leaks.\n")
	return b.String()
}

func validateSecondary(sec SecondaryConfig) error {
	if strings.TrimSpace(sec.Hostname) == "" {
		return fmt.Errorf("%w: secondary hostname is required", ErrInvalidConfig)
	}
	if strings.TrimSpace(sec.Address) == "" || strings.TrimSpace(sec.PrimaryAddress) == "" {
		return fmt.Errorf("%w: secondary and primary addresses are required", ErrInvalidConfig)
	}
	if strings.TrimSpace(sec.TSIGKeyName) == "" {
		return fmt.Errorf("%w: AXFR TSIG key name is required", ErrInvalidConfig)
	}
	for _, r := range sec.TSIGKeyName {
		ok := r == '-' || r == '.' || r == '_' ||
			(r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')
		if !ok {
			return fmt.Errorf("%w: TSIG key name %q contains invalid characters", ErrInvalidConfig, sec.TSIGKeyName)
		}
	}
	return nil
}

func secondaryZones(snap Snapshot, sec SecondaryConfig) []string {
	if len(sec.Zones) > 0 {
		zones := make([]string, 0, len(sec.Zones))
		for _, z := range sec.Zones {
			zones = append(zones, strings.ToLower(strings.TrimSuffix(z, ".")))
		}
		sort.Strings(zones)
		return zones
	}
	zones := make([]string, 0, len(snap.Zones))
	for _, z := range snap.Zones {
		zones = append(zones, strings.ToLower(strings.TrimSuffix(z.Domain, ".")))
	}
	sort.Strings(zones)
	return zones
}
