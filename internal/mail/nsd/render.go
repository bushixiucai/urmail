package nsd

import (
	"fmt"
	"sort"
	"strings"
)

// escapeZoneQuoted escapes a value for inclusion inside a double-quoted
// zone-file character string.
func escapeZoneQuoted(v string) string {
	v = strings.ReplaceAll(v, "\\\\", "\\\\")
	v = strings.ReplaceAll(v, "\"", "\\\"")
	return v
}

func renderZonesConf(snap Snapshot) string {
	zones := make([]string, 0, len(snap.Zones))
	for _, z := range snap.Zones {
		zones = append(zones, strings.ToLower(z.Domain))
	}
	sort.Strings(zones)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n\n")
	for _, domain := range zones {
		b.WriteString("zone:\n")
		b.WriteString(fmt.Sprintf("  name: %q\n", domain))
		b.WriteString(fmt.Sprintf("  zonefile: %q\n\n", domain+".txt"))
	}
	return b.String()
}

func renderZoneFile(node NodeConfig, z Zone) string {
	domain := strings.ToLower(strings.TrimSuffix(z.Domain, "."))
	primaryNS := node.Nameservers[0]
	hostmaster := fmt.Sprintf("hostmaster.%s.", node.PrimaryDomain)

	var b strings.Builder
	b.WriteString("; Generated by urmaild. DO NOT EDIT.\n")
	b.WriteString(fmt.Sprintf("$ORIGIN %s.\n", domain))
	b.WriteString("$TTL 86400\n\n")

	// SOA record
	b.WriteString(fmt.Sprintf("@ IN SOA %s. %s (\n", primaryNS, hostmaster))
	b.WriteString(fmt.Sprintf("    %d ; serial\n", z.Serial))
	b.WriteString("    7200       ; refresh (2 hours)\n")
	b.WriteString("    3600       ; retry (1 hour)\n")
	b.WriteString("    1209600    ; expire (2 weeks)\n")
	b.WriteString("    1800       ; minimum (30 mins)\n")
	b.WriteString(")\n\n")

	// NS records
	for _, ns := range node.Nameservers {
		b.WriteString(fmt.Sprintf("@ IN NS %s.\n", ns))
	}
	b.WriteString("\n")

	if z.Mode == "managed" {
		// Managed mode: Provide full standard email hosting records
		b.WriteString("; Standard Mail Server Records\n")
		b.WriteString(fmt.Sprintf("@ IN A %s\n", node.PublicIPv4))
		if node.PublicIPv6 != "" {
			b.WriteString(fmt.Sprintf("@ IN AAAA %s\n", node.PublicIPv6))
		}
		b.WriteString(fmt.Sprintf("@ IN MX 10 %s.\n", node.Hostname))
		b.WriteString("@ IN TXT \"v=spf1 mx -all\"\n")
		b.WriteString(fmt.Sprintf("_dmarc IN TXT \"v=DMARC1; p=none; rua=mailto:dmarc-reports@%s\"\n", node.PrimaryDomain))
		b.WriteString(fmt.Sprintf("mail IN A %s\n", node.PublicIPv4))
		if node.PublicIPv6 != "" {
			b.WriteString(fmt.Sprintf("mail IN AAAA %s\n", node.PublicIPv6))
		}
		b.WriteString(fmt.Sprintf("autoconfig IN CNAME %s.\n", node.Hostname))
		b.WriteString(fmt.Sprintf("autodiscover IN CNAME %s.\n", node.Hostname))
		b.WriteString("\n")
	}

	// Render any additional/custom records (e.g. DKIM, tokens)
	if len(z.Records) > 0 {
		recs := make([]Record, len(z.Records))
		copy(recs, z.Records)
		sort.Slice(recs, func(i, j int) bool {
			if recs[i].Name != recs[j].Name {
				return recs[i].Name < recs[j].Name
			}
			if recs[i].Type != recs[j].Type {
				return recs[i].Type < recs[j].Type
			}
			return recs[i].Value < recs[j].Value
		})

		b.WriteString("; Custom and Additional Records\n")
		for _, r := range recs {
			ttlStr := ""
			if r.TTL > 0 {
				ttlStr = fmt.Sprintf("%d ", r.TTL)
			}
			name := r.Name
			if name == "" {
				name = "@"
			}
			if r.Type == "MX" {
				b.WriteString(fmt.Sprintf("%s %sIN MX %d %s\n", name, ttlStr, r.Prio, r.Value))
			} else if r.Type == "TXT" {
				b.WriteString(fmt.Sprintf("%s %sIN TXT \"%s\"\n", name, ttlStr, r.Value))
			} else {
				b.WriteString(fmt.Sprintf("%s %sIN %s %s\n", name, ttlStr, r.Type, r.Value))
			}
		}
	}

	return b.String()
}
