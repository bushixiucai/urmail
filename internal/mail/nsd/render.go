package nsd

import (
	"fmt"
	"sort"
	"strings"
)

// escapeZoneQuoted escapes a value for inclusion inside a double-quoted
// zone-file character string.
func escapeZoneQuoted(v string) string {
	v = strings.ReplaceAll(v, "\\", "\\\\")
	v = strings.ReplaceAll(v, "\"", "\\\"")
	return v
}

// txtStrings renders a TXT value as one or more 255-octet character-strings.
// DNS limits each character-string to 255 bytes; DKIM public keys routinely
// exceed that and must be split or nsd-checkzone rejects the zone.
func txtStrings(value string) string {
	if len(value) <= 255 {
		return "\"" + escapeZoneQuoted(value) + "\""
	}
	var b strings.Builder
	for len(value) > 0 {
		n := 255
		if len(value) < n {
			n = len(value)
		}
		if b.Len() > 0 {
			b.WriteByte(' ')
		}
		b.WriteString("\"")
		b.WriteString(escapeZoneQuoted(value[:n]))
		b.WriteString("\"")
		value = value[n:]
	}
	return b.String()
}

func renderZonesConf(node NodeConfig, snap Snapshot) string {
	zones := make([]string, 0, len(snap.Zones))
	for _, z := range snap.Zones {
		zones = append(zones, strings.ToLower(z.Domain))
	}
	sort.Strings(zones)

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n\n")
	addresses := append([]string(nil), node.ListenAddresses...)
	if len(addresses) == 0 {
		addresses = []string{"127.0.0.1"}
	}
	sort.Strings(addresses)
	b.WriteString("server:\n")
	for _, address := range addresses {
		fmt.Fprintf(&b, "  ip-address: %s\n", address)
	}
	b.WriteString("\n")
	for _, domain := range zones {
		b.WriteString("zone:\n")
		fmt.Fprintf(&b, "  name: %q\n", domain)
		fmt.Fprintf(&b, "  zonefile: %q\n\n", "/etc/nsd/zones/"+domain+".txt")
	}
	return b.String()
}

func renderZoneFile(node NodeConfig, z Zone) string {
	domain := strings.ToLower(strings.TrimSuffix(z.Domain, "."))
	primaryNS := node.Nameservers[0]
	hostmaster := fmt.Sprintf("hostmaster.%s.", node.PrimaryDomain)

	var b strings.Builder
	b.WriteString("; Generated by urmaild. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "$ORIGIN %s.\n", domain)
	b.WriteString("$TTL 86400\n\n")

	// SOA record
	fmt.Fprintf(&b, "@ IN SOA %s. %s (\n", primaryNS, hostmaster)
	fmt.Fprintf(&b, "    %d ; serial\n", z.Serial)
	b.WriteString("    7200       ; refresh (2 hours)\n")
	b.WriteString("    3600       ; retry (1 hour)\n")
	b.WriteString("    1209600    ; expire (2 weeks)\n")
	b.WriteString("    1800       ; minimum (30 mins)\n")
	b.WriteString(")\n\n")

	// NS records
	for _, ns := range node.Nameservers {
		fmt.Fprintf(&b, "@ IN NS %s.\n", ns)
	}
	b.WriteString("\n")

	if z.Mode == "managed" {
		// Managed mode: Provide full standard email hosting records
		b.WriteString("; Standard Mail Server Records\n")
		fmt.Fprintf(&b, "@ IN A %s\n", node.PublicIPv4)
		if node.PublicIPv6 != "" {
			fmt.Fprintf(&b, "@ IN AAAA %s\n", node.PublicIPv6)
		}
		fmt.Fprintf(&b, "@ IN MX 10 %s.\n", node.Hostname)
		b.WriteString("@ IN TXT \"v=spf1 mx -all\"\n")
		fmt.Fprintf(&b, "_dmarc IN TXT \"v=DMARC1; p=none; rua=mailto:dmarc-reports@%s\"\n", node.PrimaryDomain)
		fmt.Fprintf(&b, "mail IN A %s\n", node.PublicIPv4)
		if node.PublicIPv6 != "" {
			fmt.Fprintf(&b, "mail IN AAAA %s\n", node.PublicIPv6)
		}
		fmt.Fprintf(&b, "autoconfig IN CNAME %s.\n", node.Hostname)
		fmt.Fprintf(&b, "autodiscover IN CNAME %s.\n", node.Hostname)
		b.WriteString("\n")
	}

	// Render any additional/custom records (e.g. DKIM, tokens)
	if len(z.Records) > 0 {
		recs := make([]Record, len(z.Records))
		copy(recs, z.Records)
		sort.Slice(recs, func(i, j int) bool {
			if recs[i].Name != recs[j].Name {
				return recs[i].Name < recs[j].Name
			}
			if recs[i].Type != recs[j].Type {
				return recs[i].Type < recs[j].Type
			}
			return recs[i].Value < recs[j].Value
		})

		b.WriteString("; Custom and Additional Records\n")
		for _, r := range recs {
			ttlStr := ""
			if r.TTL > 0 {
				ttlStr = fmt.Sprintf("%d ", r.TTL)
			}
			name := r.Name
			if name == "" {
				name = "@"
			}
			switch r.Type {
			case "MX":
				fmt.Fprintf(&b, "%s %sIN MX %d %s\n", name, ttlStr, r.Prio, r.Value)
			case "TXT":
				fmt.Fprintf(&b, "%s %sIN TXT %s\n", name, ttlStr, txtStrings(r.Value))
			default:
				fmt.Fprintf(&b, "%s %sIN %s %s\n", name, ttlStr, r.Type, r.Value)
			}
		}
	}

	return b.String()
}
