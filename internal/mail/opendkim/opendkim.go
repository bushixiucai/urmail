// Package opendkim renders the OpenDKIM signing configuration from the same
// domain snapshot that drives Postfix and NSD. It is a pure function: no
// database, no filesystem, no external command.
package opendkim

import (
	"fmt"
	"sort"
	"strings"

	"github.com/bushixiucai/urmail/internal/mail/validation"
)

const (
	// Root is the OpenDKIM configuration directory.
	Root = "/etc/opendkim"
	// ConfPath is the main configuration file.
	ConfPath = Root + "/opendkim.conf"
	// KeyTablePath maps a DKIM identity to a key file.
	KeyTablePath = Root + "/KeyTable"
	// SigningTablePath maps sender addresses to DKIM identities.
	SigningTablePath = Root + "/SigningTable"
	// TrustedHostsPath lists the local hosts whose mail may be signed.
	TrustedHostsPath = Root + "/TrustedHosts"
)

// DomainKey is one active domain's signing material.
type DomainKey struct {
	Domain     string
	Selector   string
	PrivateKey string // PEM
}

// Snapshot is the set of domains OpenDKIM should sign for.
type Snapshot struct {
	Domains []DomainKey
}

// NodeConfig carries node-level settings. The socket is fixed to loopback TCP
// so Postfix can reach OpenDKIM without sharing a chroot socket directory.
type NodeConfig struct {
	Socket string
}

// Generate renders the OpenDKIM configuration. Returned paths are absolute.
func Generate(node NodeConfig, snap Snapshot) (map[string]string, error) {
	if err := validate(snap); err != nil {
		return nil, err
	}
	socket := node.Socket
	if socket == "" {
		socket = "inet:12301@localhost"
	}

	domains := make([]DomainKey, len(snap.Domains))
	copy(domains, snap.Domains)
	sort.Slice(domains, func(i, j int) bool {
		return strings.ToLower(domains[i].Domain) < strings.ToLower(domains[j].Domain)
	})

	result := make(map[string]string, 4+len(domains))
	result[ConfPath] = renderConf(socket)
	result[TrustedHostsPath] = "# Generated by urmaild. DO NOT EDIT.\n127.0.0.1\n::1\nlocalhost\n"

	var keyTable, signingTable strings.Builder
	keyTable.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	signingTable.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	for _, d := range domains {
		domain := strings.ToLower(d.Domain)
		selector := strings.ToLower(d.Selector)
		keyPath := KeyPath(domain, selector)
		identity := selector + "._domainkey." + domain
		fmt.Fprintf(&keyTable, "%s %s:%s:%s\n", identity, domain, selector, keyPath)
		fmt.Fprintf(&signingTable, "*@%s %s\n", domain, identity)
		result[keyPath] = d.PrivateKey
	}
	result[KeyTablePath] = keyTable.String()
	result[SigningTablePath] = signingTable.String()
	return result, nil
}

// KeyPath is the on-disk path of a domain's signing key.
func KeyPath(domain, selector string) string {
	return Root + "/keys/" + strings.ToLower(domain) + "/" + strings.ToLower(selector) + ".private"
}

func renderConf(socket string) string {
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	b.WriteString("Syslog yes\n")
	b.WriteString("SyslogSuccess yes\n")
	b.WriteString("LogWhy yes\n")
	b.WriteString("Canonicalization relaxed/simple\n")
	b.WriteString("Mode sv\n")
	b.WriteString("SubDomains no\n")
	b.WriteString("KeyTable " + KeyTablePath + "\n")
	b.WriteString("SigningTable refile:" + SigningTablePath + "\n")
	b.WriteString("ExternalIgnoreList refile:" + TrustedHostsPath + "\n")
	b.WriteString("InternalHosts refile:" + TrustedHostsPath + "\n")
	b.WriteString("Socket " + socket + "\n")
	b.WriteString("PidFile /run/opendkim/opendkim.pid\n")
	b.WriteString("UserID opendkim\n")
	b.WriteString("UMask 007\n")
	return b.String()
}

func validate(snap Snapshot) error {
	seen := make(map[string]struct{}, len(snap.Domains))
	for _, d := range snap.Domains {
		domain := strings.ToLower(strings.TrimSpace(d.Domain))
		if d.Domain != strings.TrimSpace(d.Domain) || !validation.IsValidHostname(domain) {
			return fmt.Errorf("opendkim: invalid domain %q", d.Domain)
		}
		selector := strings.ToLower(strings.TrimSpace(d.Selector))
		if d.Selector != strings.TrimSpace(d.Selector) || !validSelector(selector) {
			return fmt.Errorf("opendkim: invalid selector %q", d.Selector)
		}
		if strings.TrimSpace(d.PrivateKey) == "" {
			return fmt.Errorf("opendkim: domain %s has no private key", domain)
		}
		key := domain + "\x00" + selector
		if _, ok := seen[key]; ok {
			return fmt.Errorf("opendkim: duplicate domain/selector %s/%s", domain, selector)
		}
		seen[key] = struct{}{}
	}
	return nil
}

func validSelector(selector string) bool {
	if selector == "" || len(selector) > 63 {
		return false
	}
	for i, r := range selector {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' || r == '_' {
			if i == 0 && (r == '-' || r == '_') {
				return false
			}
			continue
		}
		return false
	}
	return true
}
