// Package caddy renders the Caddy reverse-proxy configuration used by the
// compose topology in place of the host nginx configuration.
package caddy

import (
	"fmt"
	"sort"
	"strings"

	"github.com/bushixiucai/urmail/internal/mail/nginx"
)

// FileName is the single rendered artifact.
const FileName = "Caddyfile"

// Generate renders one site block per configured domain. TLS material follows
// the domain certificates the mail renderer already provisions.
func Generate(snapshot nginx.Snapshot) (map[string]string, error) {
	domains := append([]nginx.DomainConfig(nil), snapshot.Domains...)
	sort.Slice(domains, func(i, j int) bool { return domains[i].FQDN < domains[j].FQDN })
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n\n")
	if len(domains) == 0 {
		b.WriteString(":80 {\n  respond 503\n}\n")
	}
	for _, domain := range domains {
		fmt.Fprintf(&b, "%s {\n", domain.FQDN)
		if domain.TLSCertFile != "" && domain.TLSKeyFile != "" {
			fmt.Fprintf(&b, "  tls %s %s\n", domain.TLSCertFile, domain.TLSKeyFile)
		}
		fmt.Fprintf(&b, "  reverse_proxy 127.0.0.1:8080\n}\n\n")
	}
	return map[string]string{FileName: b.String()}, nil
}
