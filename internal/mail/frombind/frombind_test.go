package frombind

import (
	"strings"
	"testing"
)

const fixtureMap = "# Generated by urmaild. DO NOT EDIT.\n" +
	"alice@a.test\talice@a.test\n" +
	"loop@a.test\talice@a.test\n" +
	"bob@b.test\tbob@b.test\n" +
	"ceo@b.test\talice@a.test,bob@b.test\n"

func TestParseSenderLoginMap(t *testing.T) {
	m := ParseSenderLoginMap(fixtureMap)
	cases := []struct {
		login string
		want  []string
	}{
		{"alice@a.test", []string{"alice@a.test", "loop@a.test", "ceo@b.test"}},
		{"bob@b.test", []string{"bob@b.test", "ceo@b.test"}},
	}
	for _, tc := range cases {
		got := AllowedFromDomains(m[tc.login])
		for _, want := range tc.want {
			d := ExtractFromDomain(want)
			if !got[d] {
				t.Errorf("login %s: missing domain %s (got %v)", tc.login, d, got)
			}
		}
	}
	if _, ok := m["mallory@outside.test"]; ok {
		t.Error("unknown login must not exist")
	}
}

func TestParseSenderLoginMapSkipsGarbage(t *testing.T) {
	m := ParseSenderLoginMap("# comment\n\nno-tab-line\n\n")
	if len(m) != 0 {
		t.Errorf("garbage lines produced entries: %v", m)
	}
}

func TestDecideAuthenticatedSessions(t *testing.T) {
	// The fixture map grants alice@a.test the addresses alice@/loop@ (domain
	// a.test) and the delegated alias ceo@b.test (domain b.test).
	m := ParseSenderLoginMap(fixtureMap)
	allowed := AllowedFromDomains(m["alice@a.test"])

	// Spoofed From: alice claiming a foreign domain is rejected. The fixture
	// map has no third domain, so use one that no granted address carries.
	foreign := AllowedFromDomains(m["bob@b.test"])
	foreign["outside.test"] = true
	delete(foreign, "b.test")
	if d, _ := Decide(true, foreign, []string{"CEO <ceo@b.test>"}); d != RejectDomain {
		t.Errorf("spoofed From decision = %v, want RejectDomain", d)
	}
	// Own domain passes.
	if d, reason := Decide(true, allowed, []string{"Alice <alice@a.test>"}); d != Allow || reason != "ok" {
		t.Errorf("own domain decision = %v %q", d, reason)
	}
	// A delegated alias address (ceo@b.test granted to alice via explicit
	// alias senders) passes because its domain is granted to this login.
	if d, _ := Decide(true, allowed, []string{"CEO <ceo@b.test>"}); d != Allow {
		t.Errorf("delegated same-login domain decision = %v, want Allow", d)
	}
}

func TestDecideHeaderHygiene(t *testing.T) {
	allowed := map[string]bool{"a.test": true}
	if d, _ := Decide(true, allowed, nil); d != RejectMissingFrom {
		t.Errorf("missing From decision = %v", d)
	}
	if d, _ := Decide(true, allowed, []string{"<a@a.test>", "<b@a.test>"}); d != RejectMultipleFrom {
		t.Errorf("multiple From decision = %v", d)
	}
	if d, _ := Decide(true, allowed, []string{"no-domain"}); d != RejectDomain {
		t.Errorf("domainless From decision = %v", d)
	}
}

func TestDecideUnauthenticatedInboundAllowed(t *testing.T) {
	// Inbound mail from the internet carries foreign From domains; relay and
	// spoof controls are envelope-side (relay restrictions) and receiver-side
	// (SPF/DMARC), not this check.
	if d, reason := Decide(false, map[string]bool{}, []string{"CEO <ceo@b.test>"}); d != AllowUnauthenticated || reason != "unauthenticated_inbound" {
		t.Errorf("unauthenticated decision = %v %q", d, reason)
	}
}

func TestExtractFromDomainEdgeCases(t *testing.T) {
	cases := map[string]string{
		"CEO <ceo@B.TEST>": "b.test",
		"<a@x.test>":       "x.test",
		"nodomain":         "",
		"":                 "",
		"user@":            "",
	}
	for in, want := range cases {
		if got := ExtractFromDomain(in); got != want {
			t.Errorf("ExtractFromDomain(%q) = %q, want %q", in, got, want)
		}
	}
	if !strings.EqualFold(ExtractFromDomain("<a@B.Test>"), "b.test") {
		t.Error("domain extraction must lowercase")
	}
}
