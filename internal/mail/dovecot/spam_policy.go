package dovecot

import (
	"fmt"
	"sort"
	"strings"

	"github.com/bushixiucai/urmail/internal/mail/validation"
)

// SpamPolicy is a private sender rule for exactly one resolved delivery mailbox.
// It is rendered only into a root/mail-readable Sieve file, never message headers.
type SpamPolicy struct {
	MailboxAddress string
	Scope          string
	SenderAddress  string
	SenderDomain   string
	List           string
}

func validateSpamPolicies(policies []SpamPolicy) error {
	if len(policies) > 10000 {
		return fmt.Errorf("%w: too many spam policies", ErrInvalidConfig)
	}
	for _, p := range policies {
		if !validation.IsValidEmail(p.MailboxAddress) || (p.Scope != "mailbox" && p.Scope != "tenant") || (p.List != "allow" && p.List != "deny") {
			return fmt.Errorf("%w: invalid spam policy", ErrInvalidConfig)
		}
		if p.SenderAddress != "" {
			if !validation.IsValidEmail(p.SenderAddress) {
				return fmt.Errorf("%w: invalid spam sender", ErrInvalidConfig)
			}
		} else if !validation.IsValidHostname(p.SenderDomain) {
			return fmt.Errorf("%w: invalid spam domain", ErrInvalidConfig)
		}
	}
	return nil
}

func sieveLiteral(value string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(value) + `"`
}

// renderSpamSieve evaluates private rules in delivery scope before the public
// content verdict. First-match precedence is mailbox before tenant, exact sender
// before domain, and deny before allow when equally-specific old rows conflict.
func renderSpamSieve(policies []SpamPolicy) string {
	ordered := append([]SpamPolicy(nil), policies...)
	rank := func(p SpamPolicy) int {
		n := 0
		if p.Scope == "tenant" {
			n += 4
		}
		if p.SenderAddress == "" {
			n += 2
		}
		if p.List == "allow" {
			n++
		}
		return n
	}
	sort.Slice(ordered, func(i, j int) bool {
		a, b := ordered[i], ordered[j]
		if a.MailboxAddress != b.MailboxAddress {
			return a.MailboxAddress < b.MailboxAddress
		}
		if rank(a) != rank(b) {
			return rank(a) < rank(b)
		}
		if a.SenderAddress != b.SenderAddress {
			return a.SenderAddress < b.SenderAddress
		}
		return a.SenderDomain < b.SenderDomain
	})
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n# Private recipient-scoped sender policies. Never expose this file to mailbox clients.\n")
	b.WriteString("require \"vnd.dovecot.execute\";\n")
	b.WriteString("require [\"fileinto\", \"mailbox\", \"envelope\", \"variables\", \"relational\", \"comparator-i;ascii-numeric\", \"imap4flags\"];\nset \"urmail_spam_rule\" \"none\";\n")
	for _, p := range ordered {
		sender := `address :is "from" ` + sieveLiteral(p.SenderAddress)
		if p.SenderAddress == "" {
			sender = `address :domain :is "from" ` + sieveLiteral(p.SenderDomain)
		}
		fmt.Fprintf(&b, "if allof (string :is \"${urmail_spam_rule}\" \"none\", envelope :is \"to\" %s, address :count \"eq\" :comparator \"i;ascii-numeric\" \"from\" \"1\", %s) { set \"urmail_spam_rule\" %s; }\n", sieveLiteral(p.MailboxAddress), sender, sieveLiteral(p.List))
	}
	// Allow skips only the shared spam decision, not the user's filters/vacation.
	// Deny marks as spam with addflag and never discards or rejects a message.
	b.WriteString("if anyof (string :is \"${urmail_spam_rule}\" \"deny\", allof (not string :is \"${urmail_spam_rule}\" \"allow\", header :is \"X-UrMail-Spam\" \"yes\")) {\n  addflag \"urmail_spam\";\n}\n")
	b.WriteString("# Live outbound gate: fileinto cancels implicit keep and stops the multi-script chain.\nif not execute \"outbound-check\" { fileinto \"INBOX\"; stop; }\n")
	return b.String()
}

// renderSpamAfterSieve files into Junk if hasflag "urmail_spam" and implicit keep is still active.
func renderSpamAfterSieve() string {
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	b.WriteString("require [\"fileinto\", \"mailbox\", \"imap4flags\"];\n")
	b.WriteString("if hasflag \"urmail_spam\" {\n  fileinto :create \"Junk\";\n  stop;\n}\n")
	return b.String()
}
