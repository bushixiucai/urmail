package dovecot

import "github.com/bushixiucai/urmail/internal/mail/sievegate"

// Dovecot configuration file names relative to /etc/dovecot.
const (
	FileGlobalACL        = "conf.d/urmail-global-acls"
	FileAuthConf         = "conf.d/10-auth.conf"
	FileDovecotConf      = "conf.d/urmail/dovecot.conf"
	FileDovecotSQL       = "conf.d/urmail/dovecot-sql.conf.ext"
	FileDBConf           = "conf.d/urmail/db.conf"
	FileDovecotMailboxes = "conf.d/urmail/dovecot-mailboxes.conf.ext"
	FileDovecotQuota     = "conf.d/urmail/dovecot-quota.conf.ext"
	// FileSpamSieve is the global before-script referenced by the
	// sieve_before line rendered into dovecot.conf (MAIL-002). It lives
	// under /etc/dovecot/conf.d, which is already an agent write root.
	FileSpamSieve       = "urmail-spam/spam-before.sieve"
	FileSpamAfterSieve  = "urmail-spam/spam-after.sieve"
	FileSieveGateHelper = "urmail-spam/execute/outbound-check"
)

// Generate is a pure function that renders Dovecot configuration files.
// Output keys represent paths relative to /etc/dovecot.
// Returns the service configuration and an explicit replacement for stock OS authentication.
func Generate(node NodeConfig) (map[string]string, error) {
	if err := Validate(node); err != nil {
		return nil, err
	}

	result := make(map[string]string, 7)
	result[FileGlobalACL] = "# Generated by urmaild. DO NOT EDIT.\n* group-override=expired lrstex\n"
	result[FileAuthConf] = "# Generated by urmaild. DO NOT EDIT.\n# Authentication is defined exclusively by conf.d/urmail/dovecot-sql.conf.ext.\n"
	result[FileDovecotConf] = renderDovecotConf(node)
	result[FileDovecotSQL] = renderDovecotSQL(node)
	result[FileDBConf] = renderDBConf(node)
	result[FileDovecotMailboxes] = renderDovecotMailboxes()
	result[FileDovecotQuota] = renderDovecotQuota()
	result[FileSpamSieve] = renderSpamSieve(node.SpamPolicies)
	result[FileSpamAfterSieve] = renderSpamAfterSieve()
	result[FileSieveGateHelper] = sievegate.HelperScript

	return result, nil
}
