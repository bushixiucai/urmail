var update = flag.Bool("update", false, "update golden files")

func defaultNodeConfig() dovecot.NodeConfig {
	return dovecot.NodeConfig{
		Hostname:      "box.urmail.cn",
		PrimaryDomain: "urmail.cn",
		StorageRoot:   "/var/mail",
		TLSCertFile:   "/var/mail/ssl/box.urmail.cn.cert",
		TLSKeyFile:    "/var/mail/ssl/box.urmail.cn.key",
		DatabaseURL:   "host=127.0.0.1 dbname=urmail user=urmail_dovecot password=secret sslmode=disable",
		MailUID:       "mail",
		MailGID:       "mail",
	}
}

// TestPureFunctionConstraint guarantees that the dovecot package does not import
// database/sql or os/exec.
func TestPureFunctionConstraint(t *testing.T) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, ".", nil, parser.ImportsOnly) //nolint:staticcheck // Source-only import policy intentionally includes all build variants.
	if err != nil {
		t.Fatalf("parse dovecot package: %v", err)
	}

	disallowed := map[string]bool{
		"database/sql": true,
		"os/exec":      true,
		"os":           true,
	}

	for _, pkg := range pkgs {
		for filename, file := range pkg.Files {
			if strings.HasSuffix(filename, "_test.go") {
				continue
			}
			for _, imp := range file.Imports {
				path := strings.Trim(imp.Path.Value, `"`)
				if disallowed[path] {
					t.Errorf("file %s imports disallowed package %s (generator must be pure)", filename, path)
				}
			}
		}
	}
}

func TestGoldenCases(t *testing.T) {
	cases := []struct {
		name string
		node dovecot.NodeConfig
	}{
		{
			name: "standard",
			node: defaultNodeConfig(),
		},
		{
			name: "custom_storage_and_user",
			node: func() dovecot.NodeConfig {
				n := defaultNodeConfig()
				n.StorageRoot = "/mnt/storage/mail"
				n.MailUID = "vmail"
				n.MailGID = "vmail"
				return n
			}(),
		},
	}

	expectedFiles := []struct {
		key      string
		filename string
	}{
		{dovecot.FileGlobalACL, "global-acls"},
		{dovecot.FileAuthConf, "10-auth.conf"},
		{dovecot.FileDovecotConf, "dovecot.conf"},
		{dovecot.FileDovecotSQL, "dovecot-sql.conf.ext"},
		{dovecot.FileDBConf, "db.conf"},
		{dovecot.FileDovecotMailboxes, "dovecot-mailboxes.conf.ext"},
		{dovecot.FileDovecotQuota, "dovecot-quota.conf.ext"},
		{dovecot.FileSpamSieve, "spam-before.sieve"},
		{dovecot.FileSpamAfterSieve, "spam-after.sieve"},
		{dovecot.FileSieveGateHelper, "outbound-check"},
	}

	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			out, err := dovecot.Generate(tc.node)
			if err != nil {
				t.Fatalf("Generate failed: %v", err)
			}

			if len(out) != len(expectedFiles) {
				t.Fatalf("unexpected configuration file count: %d", len(out))
			}

			goldenDir := filepath.Join("testdata", "golden", tc.name)
			if *update {
				if err := os.MkdirAll(goldenDir, 0o755); err != nil {
					t.Fatalf("mkdir %s: %v", goldenDir, err)
				}
			}

			for _, ef := range expectedFiles {
				content, ok := out[ef.key]
				if !ok {
					t.Errorf("missing key %s", ef.key)
					continue
				}
				if !strings.HasSuffix(content, "\n") {
					t.Errorf("%s does not end with newline", ef.key)
				}
				if !strings.HasPrefix(strings.TrimPrefix(content, "#!/usr/bin/python3 -I\n"), "# Generated by urmaild. DO NOT EDIT.\n") {
					t.Errorf("%s missing header banner", ef.key)
				}

				goldenFile := filepath.Join(goldenDir, ef.filename)
				if *update {
					if err := os.WriteFile(goldenFile, []byte(content), 0o644); err != nil {
						t.Fatalf("write golden file %s: %v", goldenFile, err)
					}
				} else {
					expected, err := os.ReadFile(goldenFile)
					if err != nil {
						t.Fatalf("read golden file %s: %v", goldenFile, err)
					}
					if string(expected) != content {
						t.Errorf("mismatch in %s:\n--- Expected ---\n%s\n--- Got ---\n%s", ef.filename, string(expected), content)
					}
				}
			}
		})
	}
}

func TestErrorPaths(t *testing.T) {
	node := defaultNodeConfig()

	t.Run("invalid_hostname", func(t *testing.T) {
		bad := node
		bad.Hostname = "invalid_host"
		_, err := dovecot.Generate(bad)
		if err == nil || !strings.Contains(err.Error(), dovecot.ErrInvalidConfig.Error()) {
			t.Errorf("expected ErrInvalidConfig, got %v", err)
		}
	})

	t.Run("empty_storage_root", func(t *testing.T) {
		bad := node
		bad.StorageRoot = "  "
		_, err := dovecot.Generate(bad)
		if err == nil || !strings.Contains(err.Error(), dovecot.ErrInvalidConfig.Error()) {
			t.Errorf("expected ErrInvalidConfig, got %v", err)
		}
	})

	t.Run("empty_database_url", func(t *testing.T) {
		bad := node
		bad.DatabaseURL = ""
		_, err := dovecot.Generate(bad)
		if err == nil || !strings.Contains(err.Error(), dovecot.ErrInvalidConfig.Error()) {
			t.Errorf("expected ErrInvalidConfig, got %v", err)
		}
	})
}
