package dovecot

import (
	"fmt"
	"strings"
)

func renderDovecotConf(node NodeConfig) string {
	mailUID := node.MailUID
	if mailUID == "" {
		mailUID = "mail"
	}
	mailGID := node.MailGID
	if mailGID == "" {
		mailGID = "mail"
	}
	storageRoot := strings.TrimRight(node.StorageRoot, "/")

	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n\n")
	b.WriteString("# Protocols and Core\n")
	b.WriteString("protocols = imap pop3 lmtp sieve\n")
	b.WriteString("mail_plugins = quota acl\n")
	b.WriteString("listen = *\n")
	b.WriteString("default_process_limit = 250\n")
	b.WriteString("default_client_limit = 1000\n\n")

	b.WriteString("# Authentication\n")
	b.WriteString("disable_plaintext_auth = yes\n")
	b.WriteString("auth_mechanisms = plain login\n")
	// MAIL-003: slow repeated password guessing on IMAP/POP3. The delay is
	// per authentication attempt failure and is part of the generated policy,
	// so it is reinstated on every service restart (durable protection).
	b.WriteString("auth_failure_delay = 2 secs\n\n")

	b.WriteString("!include /etc/dovecot/conf.d/urmail/dovecot-sql.conf.ext\n\n")

	b.WriteString("# Mail Location and Permissions\n")
	fmt.Fprintf(&b, "mail_location = maildir:%s/mail/mailboxes/%%d/%%n\n", storageRoot)
	fmt.Fprintf(&b, "mail_uid = %s\n", mailUID)
	fmt.Fprintf(&b, "mail_gid = %s\n", mailGID)
	b.WriteString("first_valid_uid = 0\n\n")

	b.WriteString("# TLS / SSL Settings\n")
	b.WriteString("ssl = required\n")
	fmt.Fprintf(&b, "ssl_cert = <%s\n", node.TLSCertFile)
	fmt.Fprintf(&b, "ssl_key = <%s\n", node.TLSKeyFile)
	b.WriteString("ssl_min_protocol = TLSv1.2\n")
	b.WriteString("ssl_cipher_list = ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384\n")
	b.WriteString("ssl_prefer_server_ciphers = no\n\n")

	b.WriteString("# LMTP and Postfix SASL Services\n")
	b.WriteString("service lmtp {\n")
	if node.V80Preserve {
		b.WriteString("  inet_listener lmtp {\n    address = 127.0.0.1\n    port = 10026\n  }\n")
	}
	b.WriteString("  unix_listener /var/spool/postfix/private/dovecot-lmtp {\n")
	b.WriteString("    mode = 0660\n")
	b.WriteString("    user = postfix\n")
	b.WriteString("    group = postfix\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")

	b.WriteString("service auth {\n")
	b.WriteString("  unix_listener /var/spool/postfix/private/auth {\n")
	b.WriteString("    mode = 0660\n")
	b.WriteString("    user = postfix\n")
	b.WriteString("    group = postfix\n")
	b.WriteString("  }\n")
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "plugin {\n  sieve = file:%s/sieve/%%u.sieve\n", storageRoot)
	// MAIL-002: the global before-script runs BEFORE the user's own script
	// and evaluates recipient-scoped sender rules before shared classification.
	// Both managed and legacy mailboxes inherit this entry point; imported
	// global/user scripts remain subsequent hooks.
	b.WriteString("  sieve_before = /etc/dovecot/urmail-spam/spam-before.sieve\n")
	b.WriteString("}\n\n")
	b.WriteString("!include /etc/dovecot/conf.d/urmail/dovecot-mailboxes.conf.ext\n")
	b.WriteString("!include /etc/dovecot/conf.d/urmail/dovecot-quota.conf.ext\n")

	return b.String()
}

func renderDovecotSQL(_ NodeConfig) string {
	var b strings.Builder
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n\n")
	b.WriteString("passdb {\n")
	b.WriteString("  driver = sql\n")
	b.WriteString("  args = /etc/dovecot/conf.d/urmail/db.conf\n")
	b.WriteString("}\n\n")
	b.WriteString("userdb {\n")
	b.WriteString("  driver = sql\n")
	b.WriteString("  args = /etc/dovecot/conf.d/urmail/db.conf\n")
	b.WriteString("}\n")
	return b.String()
}

func renderDBConf(node NodeConfig) string {
	mailUID := node.MailUID
	if mailUID == "" {
		mailUID = "mail"
	}
	mailGID := node.MailGID
	if mailGID == "" {
		mailGID = "mail"
	}
	storageRoot := strings.TrimRight(node.StorageRoot, "/")

	var b strings.Builder
	// CONTRACT: renderDBConf output (db.conf) embeds node.DatabaseURL, which
	// carries database credentials. Every writer of this file (urmailctl
	// config render, agentd file.write) MUST persist it with mode 0640 and
	// owner root:dovecot. Do not render the URL anywhere else.
	b.WriteString("# Generated by urmaild. DO NOT EDIT.\n")
	b.WriteString("# Permissions must be 0640 root:dovecot\n\n")
	b.WriteString("driver = pgsql\n")
	fmt.Fprintf(&b, "connect = %s\n", node.DatabaseURL)
	b.WriteString("default_pass_scheme = SHA512-CRYPT\n\n")
	b.WriteString("password_query = SELECT m.address AS user, m.password_hash AS password FROM mailboxes m JOIN tenants t ON t.id = m.tenant_id JOIN domains d ON d.id = m.domain_id AND d.tenant_id = m.tenant_id WHERE m.address = '%u' AND m.status = 'active' AND t.status = 'active' AND d.status = 'active' AND urmail_domain_mail_ready(m.tenant_id,m.domain_id);\n\n")
	fmt.Fprintf(&b, "user_query = SELECT m.address AS user, '%s' AS uid, '%s' AS gid, '%s/mail/mailboxes/%%d/%%n' AS home, '*:bytes=' || CASE WHEN m.quota_bytes = -1 THEN '0' ELSE m.quota_bytes::text END AS quota_rule, CASE WHEN urmail_mail_readable(m.tenant_id) THEN '' ELSE 'expired' END AS acl_groups, %s FROM mailboxes m JOIN tenants t ON t.id = m.tenant_id JOIN domains d ON d.id = m.domain_id AND d.tenant_id = m.tenant_id WHERE m.address = '%%u' AND ((m.status = 'active' AND t.status = 'active' AND d.status = 'active' AND urmail_domain_mail_ready(m.tenant_id,m.domain_id)) OR '%%s' = 'doveadm');\n\n", mailUID, mailGID, storageRoot, legacySieveUserFields(storageRoot))
	b.WriteString("iterate_query = SELECT m.address AS user FROM mailboxes m JOIN tenants t ON t.id = m.tenant_id JOIN domains d ON d.id = m.domain_id AND d.tenant_id = m.tenant_id WHERE m.status = 'active' AND t.status = 'active' AND d.status = 'active' AND urmail_domain_mail_ready(m.tenant_id,m.domain_id);\n")
	return b.String()
}

