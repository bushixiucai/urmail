#!/usr/bin/env python3
"""gen_sqlc_overrides.py — keep sqlc's SQLite type mapping identical to the
PG-era generated models.

Why this exists
---------------
sqlc's SQLite engine maps every INTEGER column to int64 and every nullable TEXT
column to sql.NullString. The store package, however, was generated against the
PostgreSQL schema with `sql_package: pgx/v5`, so it carries time.Time /
pgtype.* / bool / int32 / []string / *netip.Addr — and the whole codebase is
written against those types. Without per-column overrides the engine switch
would rewrite ~700 model fields and every call site with them (that is the
separate B5b int64 sweep).

This script derives the overrides from the checked-in models.go: each struct's
json tags are the column names, so the field type is exactly the type sqlc must
keep emitting for that column. It writes the `overrides:` block into sqlc.yaml.

Usage:
  python3 scripts/sqlite/gen_sqlc_overrides.py            # rewrite sqlc.yaml
  python3 scripts/sqlite/gen_sqlc_overrides.py --check    # exit 1 if stale
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "migrations_sqlite" / "0001_init.sql"
MODELS = ROOT / "internal" / "store" / "models.go"
TIMESTAMPS = ROOT / "scripts" / "sqlite" / "timestamp-columns.txt"
SQLC = ROOT / "sqlc.yaml"

HEADER = "# Generated by scripts/sqlite/gen_sqlc_overrides.py — do not edit by hand."
BEGIN = "        # >>> generated overrides (scripts/sqlite/gen_sqlc_overrides.py)\n        overrides:"
END = "        # <<< generated overrides"


def schema_columns():
    """table -> ordered [(column, declared type, not_null)] from 0001_init.sql."""
    src = SCHEMA.read_text()
    out = {}
    for m in re.finditer(r'CREATE TABLE IF NOT EXISTS "(\w+)" \((.*?)\n\);', src, re.S):
        table, body = m.group(1), m.group(2)
        cols = []
        for line in body.split("\n"):
            line = line.strip().rstrip(",")
            cm = re.match(r'"(\w+)"\s+([A-Z]+)(.*)$', line)
            if not cm:
                continue
            col, decl, rest = cm.group(1), cm.group(2), cm.group(3)
            upper = rest.upper()
            not_null = "NOT NULL" in upper or "PRIMARY KEY" in upper
            cols.append((col, decl, not_null))
        out[table] = cols
    # Incremental migrations add columns after the initial schema; include
    # them so a struct with the new column still matches its table.
    for path in sorted(SCHEMA.parent.glob("*.sql")):
        if path.name == SCHEMA.name:
            continue
        for m in re.finditer(r'(?im)ALTER\s+TABLE\s+"?(\w+)"?\s+ADD\s+COLUMN\s+"?(\w+)"?\s+([A-Z]+)([^;]*)', path.read_text()):
            table, col, decl, rest = m.group(1), m.group(2), m.group(3), m.group(4)
            upper = rest.upper()
            not_null = "NOT NULL" in upper
            if table in out:
                out[table].append((col, decl, not_null))
    return out


def model_fields():
    """struct -> [(json tag, Go type)] from models.go."""
    src = MODELS.read_text()
    out = {}
    for m in re.finditer(r'(?m)^type (\w+) struct \{\n(.*?)\n\}', src, re.S):
        struct, body = m.group(1), m.group(2)
        fields = []
        for line in body.split("\n"):
            fm = re.match(r'\s*(\w+)\s+(\S+)\s+`json:"(\w+)"', line)
            if not fm:
                continue
            fields.append((fm.group(3), fm.group(2)))
        out[struct] = fields
    return out


def default_go_type(decl, not_null):
    if decl == "TEXT":
        return "string" if not_null else "sql.NullString"
    if decl == "INTEGER":
        return "int64" if not_null else "sql.NullInt64"
    if decl == "REAL":
        return "float64" if not_null else "sql.NullFloat64"
    if decl == "BLOB":
        return "[]byte"
    return None


def go_type_yaml(go_type):
    if go_type.startswith("*netip."):
        return (
            "            go_type:\n"
            "              import: net/netip\n"
            f"              type: {go_type[len('*netip.'):]}\n"
            "              pointer: true"
        )
    if go_type.startswith("*"):
        raise SystemExit(f"unsupported pointer type in models.go: {go_type}")
    # sqlc rejects a bare "[]string"/"[]int64" as "not a Go basic type"; the
    # object form with slice: true is the documented way to emit a slice.
    if go_type.startswith("[]") and go_type != "[]byte":
        return (
            "            go_type:\n"
            f'              type: "{go_type[2:]}"\n'
            "              slice: true"
        )
    if go_type == "[]byte":
        return '            go_type:\n              type: "byte"\n              slice: true'
    if "." in go_type:
        pkg, name = go_type.split(".", 1)
        imports = {
            "pgtype": "github.com/jackc/pgx/v5/pgtype",
            "time": "time",
            "netip": "net/netip",
            "sql": "database/sql",
        }
        return (
            "            go_type:\n"
            f"              import: {imports[pkg]}\n"
            f"              type: {name}"
        )
    return f'            go_type: "{go_type}"'


def timestamp_columns():
    """Columns the SQLite engine stores as INTEGER unix microseconds.

    B5b: timestamps are plain int64 everywhere (0 = zero value), so they are
    forced to int64 regardless of nullability — sqlc would otherwise emit
    sql.NullInt64 for nullable columns and force every call site back into a
    wrapper struct.
    """
    out = set()
    for line in TIMESTAMPS.read_text().split("\n"):
        line = line.split("#", 1)[0].strip()
        if line:
            out.add(line)
    return out


def build_overrides():
    tables = schema_columns()
    models = model_fields()
    timestamps = timestamp_columns()
    mismatches = []
    overrides = []
    # Match a struct to a table by its json-tag set; sqlc keeps the tag set equal
    # to the table's column set for whole-table models.
    tag_sets = {t: frozenset(c[0] for c in cols) for t, cols in tables.items()}
    for struct, fields in models.items():
        tags = frozenset(tag for tag, _ in fields)
        candidates = [t for t, s in tag_sets.items() if s == tags]
        if len(candidates) != 1:
            continue
        table = candidates[0]
        types_by_col = dict(fields)
        for col, decl, not_null in tables[table]:
            go_type = types_by_col.get(col)
            if go_type is None:
                continue
            if f"{table}.{col}" in timestamps:
                overrides.append((table, col, "int64"))
                continue
            want = default_go_type(decl, not_null)
            if want is None or go_type == want:
                continue
            if want == "string" and go_type == "string":
                continue
            # A nullable column the PG schema made non-null (or the reverse) is
            # a schema-generation discrepancy, not a type choice.
            if go_type in ("string", "int64", "float64") and want != go_type:
                mismatches.append((table, col, decl, not_null, go_type, want))
                continue
            overrides.append((table, col, go_type))
    missing = sorted(t for t in timestamps if t not in
                     {f"{tb}.{c}" for tb, cols in tables.items() for c, _, _ in cols})
    if missing:
        print("timestamp-columns.txt names missing columns: " + ", ".join(missing), file=sys.stderr)
    for m in mismatches:
        print("schema/nullability mismatch: %s.%s %s not_null=%s model=%s sqlite=%s" % m, file=sys.stderr)
    return overrides, mismatches


def render(overrides):
    lines = [BEGIN]
    for table, col, go_type in overrides:
        lines.append(f'          - column: "{table}.{col}"')
        lines.append(go_type_yaml(go_type))
    lines.append(END)
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    overrides, mismatches = build_overrides()
    block = render(overrides)
    src = SQLC.read_text()
    if BEGIN in src:
        start = src.index(BEGIN)
        end = src.index(END) + len(END)
        new = src[:start] + block.rstrip("\n") + src[end:]
    else:
        # insert after emit_empty_slices (end of gen.go block)
        anchor = "        emit_empty_slices: true\n"
        if anchor not in src:
            raise SystemExit("sqlc.yaml: emit_empty_slices anchor missing")
        new = src.replace(anchor, anchor + block, 1)
    if args.check:
        if new != src:
            print("sqlc.yaml overrides are stale; run scripts/sqlite/gen_sqlc_overrides.py", file=sys.stderr)
            return 1
        print(f"sqlc overrides up to date ({len(overrides)} columns)")
        return 0
    SQLC.write_text(new)
    print(f"wrote {len(overrides)} column overrides to sqlc.yaml" + (f" ({len(mismatches)} mismatches skipped)" if mismatches else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())