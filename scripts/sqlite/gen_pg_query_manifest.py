#!/usr/bin/env python3
"""Generate a stable method-name -> PostgreSQL SQL map from isolated sqlc output."""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
PG_DIR = ROOT / "internal/store/generated/postgres"
OUTPUT = PG_DIR / "query_manifest.go"
CONST_RE = re.compile(r"const\s+\w+\s+=\s+`(.*?)`", re.S)
NAME_RE = re.compile(r"(?m)^-- name:\s+(\w+)\s+:")


def generated_source(pg_dir: Path) -> str:
    queries: dict[str, str] = {}
    for path in sorted(pg_dir.glob("*.sql.go")):
        text = path.read_text()
        for match in CONST_RE.finditer(text):
            sql = match.group(1)
            named = NAME_RE.search(sql)
            if not named:
                continue
            method = named.group(1)
            prior = queries.get(method)
            if prior is not None and prior != sql:
                raise SystemExit(f"duplicate PostgreSQL sqlc query name: {method}")
            queries[method] = sql
    if not queries:
        raise SystemExit(f"no PostgreSQL sqlc queries found under {pg_dir}")
    rows = ["// Code generated by scripts/sqlite/gen_pg_query_manifest.py; DO NOT EDIT.",
            "package storepg", "", "var queryManifest = map[string]string{"]
    for method, sql in sorted(queries.items()):
        if "`" in sql:
            raise SystemExit(f"raw backtick in PostgreSQL query {method}; cannot emit manifest")
        rows.append(f"\t{method!r}: `{sql}`,".replace("'", '"', 2))
    rows.extend(["}", "", "// QuerySQL returns the PostgreSQL statement for a sqlc method name.",
                 "func QuerySQL(method string) (string, bool) {", "\tsql, ok := queryManifest[method]",
                 "\treturn sql, ok", "}", ""])
    return "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--source-dir", type=Path, default=PG_DIR)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    expected = generated_source(args.source_dir)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != expected:
            print(f"PostgreSQL query manifest drift (source {args.source_dir})", file=sys.stderr)
            return 1
        print(f"PostgreSQL query manifest up to date ({len(queryManifestNames(expected))} methods)")
        return 0
    args.output.write_text(expected)
    print(f"wrote PostgreSQL query manifest ({len(queryManifestNames(expected))} methods)")
    return 0


def queryManifestNames(src: str) -> set[str]:
    return set(re.findall(r'^\t"(\w+)":', src, re.M))


if __name__ == "__main__":
    raise SystemExit(main())
