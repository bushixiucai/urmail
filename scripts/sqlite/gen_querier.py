#!/usr/bin/env python3
"""gen_querier.py — rebuild internal/store/querier.go as the union of the
whole *Queries surface, deterministically.

Why not let sqlc write it? During B5a sqlc only sees the tenant query set:
the 58 platform-only files are blocked in b5-blocked-files.json and excluded
from sqlc.yaml. Their `.sql.go` files still exist (they keep compiling until
S4 rewrites them), so a sqlc-written querier.go would silently drop ~450
blocked methods and the interface would no longer describe the real surface.

So the interface is derived from the actual methods in the package:
generated `*.sql.go`, the handwritten sqlite layer (`sqlite_methods.go`) and
the restored parameter types (`sqlite_params.go`). Methods are sorted, each
keeps its doc comment (minus the `scope:` annotation lines), and the
compile-time assertion `var _ Querier = (*Queries)(nil)` is appended so a
signature drift cannot pass the build.

  python3 scripts/sqlite/gen_querier.py          # rewrite querier.go
  python3 scripts/sqlite/gen_querier.py --check  # fail if it is stale
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
STORE = ROOT / "internal" / "store"
OUT = STORE / "querier.go"

FUNC_LINE = re.compile(r"(?m)^func \(q \*Queries\) (\w+)\(")


def sources():
    files = sorted(STORE.glob("*.sql.go"))
    for extra in ("sqlite_methods.go", "sqlite_params.go"):
        p = STORE / extra
        if p.exists():
            files.append(p)
    return files


def methods():
    found = {}
    for path in sources():
        lines = path.read_text().split("\n")
        for i, line in enumerate(lines):
            m = FUNC_LINE.match(line)
            if not m:
                continue
            name = m.group(1)
            if not name[0].isupper() or name in found:
                continue  # interface = exported query surface only
            # Collect the contiguous comment block directly above the func,
            # skipping the scope annotation that sqlc copies into the body.
            docs = []
            j = i - 1
            while j >= 0 and lines[j].startswith("//"):
                text = lines[j][2:].strip()
                if text and not text.startswith("scope:"):
                    docs.append(text)
                j -= 1
            docs.reverse()
            # Signatures may be wrapped over several lines; join until the
            # parameter list balances, then drop the body brace.
            sig = line[len("func (q *Queries) "):]
            k = i
            depth = sig.count("(") - sig.count(")")
            while depth > 0 and k + 1 < len(lines):
                k += 1
                sig += " " + lines[k].strip()
                depth += lines[k].count("(") - lines[k].count(")")
            sig = sig.rstrip()
            sig = re.sub(r"\s*\{.*$", "", sig).rstrip()
            found[name] = (docs, sig)
    return found


def render(found):
    body = []
    for name in sorted(found):
        docs, sig = found[name]
        for d in docs:
            body.append("\t// " + d)
        body.append("\t" + sig)
    return (
        "// Code generated by scripts/sqlite/gen_querier.py. DO NOT EDIT.\n"
        "\n"
        "package store\n"
        "\n"
        "import (\n"
        '\t"context"\n'
        "\n"
        '\t"github.com/jackc/pgx/v5/pgtype"\n'
        ")\n"
        "\n"
        "// Querier is the union of every *Queries method in this package: sqlc\n"
        "// generation for the tenant query set, the handwritten SQLite layer, and\n"
        "// the still-compiling platform `.sql.go` files blocked in\n"
        "// scripts/sqlite/b5-blocked-files.json.\n"
        "type Querier interface {\n"
        + "\n".join(body) + "\n"
        "}\n"
        "\n"
        "var _ Querier = (*Queries)(nil)\n"
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    found = methods()
    out = render(found)
    current = OUT.read_text() if OUT.exists() else ""
    if args.check:
        if out != current:
            print("querier.go is stale: run scripts/sqlite/gen_querier.py", file=sys.stderr)
            return 1
        print(f"querier.go up to date ({len(found)} methods)")
        return 0
    OUT.write_text(out)
    print(f"wrote querier.go ({len(found)} methods)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())