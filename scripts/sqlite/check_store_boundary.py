#!/usr/bin/env python3
"""check_store_boundary.py — S2/S3 post-sqlc store.New / WithTx boundary & isolation sync.

Enforces five invariants from v3.2 §2.1:
  1. internal/db/isolation/method_scopes.json stays byte-identical to
     scripts/sqlite/method_scopes.json.
  2. Every method on store.Querier (internal/store/querier.go) is registered in
     internal/db/isolation/method_scopes.json.
  3. Non-test Go code outside internal/db/store.go has zero direct `store.New(`
     calls (all production callers assemble through db.Queries(tx) / db.Querier(tx)).
  4. Non-test Go code outside internal/store/sqlite_methods.go has zero direct
     `.WithTx(` calls (exact total == 1 inside runTx), and internal/store/db.go
     preserves the boundary comment on func New and the txBoundaryHook /
     boundaryHook isolation guard on (*Queries).WithTx.
  5. Both sync & --check modes run cleanly without mutating the tree on --check.

Usage:
  python3 scripts/sqlite/check_store_boundary.py          # sync isolation json & guard db.go, then verify
  python3 scripts/sqlite/check_store_boundary.py --check  # read-only verification (for make sqlc-check / CI)
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC_SCOPES = ROOT / "scripts" / "sqlite" / "method_scopes.json"
DST_SCOPES = ROOT / "internal" / "db" / "isolation" / "method_scopes.json"
STORE_DB_GO = ROOT / "internal" / "store" / "db.go"
QUERIER_GO = ROOT / "internal" / "store" / "querier.go"
ALLOWED_STORE_NEW_FILE = "internal/db/store.go"
ALLOWED_WITH_TX_FILE = "internal/store/sqlite_methods.go"

STORE_DB_GO_TEMPLATE = """// Code generated by sqlc. DO NOT EDIT.
// versions:
//   sqlc v1.30.0

package store

import (
\t"context"
\t"sync"

\t"github.com/jackc/pgx/v5"
\t"github.com/jackc/pgx/v5/pgconn"
)

type DBTX interface {
\tExec(context.Context, string, ...interface{}) (pgconn.CommandTag, error)
\tQuery(context.Context, string, ...interface{}) (pgx.Rows, error)
\tQueryRow(context.Context, string, ...interface{}) pgx.Row
}

var (
\ttxBoundaryMu   sync.RWMutex
\ttxBoundaryHook func(DBTX, *Queries) *Queries
)

// SetTxBoundaryHook installs the isolation boundary hook applied by
// (*Queries).WithTx so transaction-derived queries cannot bypass db.Queries.
func SetTxBoundaryHook(hook func(DBTX, *Queries) *Queries) {
\ttxBoundaryMu.Lock()
\ttxBoundaryHook = hook
\ttxBoundaryMu.Unlock()
}

func currentTxBoundaryHook() func(DBTX, *Queries) *Queries {
\ttxBoundaryMu.RLock()
\th := txBoundaryHook
\ttxBoundaryMu.RUnlock()
\treturn h
}

// New constructs Queries. Production callers must use db.Queries
// (internal/db/store.go), the single assembly point (v3.2 §2.1).
func New(db DBTX) *Queries {
\treturn &Queries{db: db}
}

type Queries struct {
\tdb           DBTX
\tboundaryHook func(DBTX, *Queries) *Queries
}

// AttachBoundary binds the assembly boundary hook onto q so subsequent WithTx
// calls preserve identical isolation checks.
func (q *Queries) AttachBoundary(hook func(DBTX, *Queries) *Queries) *Queries {
\tif q == nil {
\t\treturn nil
\t}
\tq.boundaryHook = hook
\treturn q
}

// WrapDB replaces q's underlying DBTX through wrap without creating an
// unguarded Queries instance.
func (q *Queries) WrapDB(wrap func(DBTX) DBTX) *Queries {
\tif q == nil {
\t\treturn nil
\t}
\tif wrap == nil {
\t\tpanic("store.Queries.WrapDB: nil wrapper")
\t}
\twrapped := wrap(q.db)
\tif wrapped == nil {
\t\tpanic("store.Queries.WrapDB: wrapper returned nil DBTX")
\t}
\tq.db = wrapped
\treturn q
}

// WithTx derives a transaction-bound *Queries through the active db.Queries /
// isolation boundary (v3.2 §2.1).
func (q *Queries) WithTx(tx pgx.Tx) *Queries {
\tif tx == nil {
\t\tpanic("store.Queries.WithTx: nil pgx.Tx")
\t}
\tvar hook func(DBTX, *Queries) *Queries
\tif q != nil {
\t\thook = q.boundaryHook
\t}
\tif hook == nil {
\t\thook = currentTxBoundaryHook()
\t}
\tderived := &Queries{
\t\tdb:           tx,
\t\tboundaryHook: hook,
\t}
\tif hook != nil {
\t\tif wrapped := hook(tx, derived); wrapped != nil {
\t\t\twrapped.boundaryHook = hook
\t\t\treturn wrapped
\t\t}
\t}
\treturn derived
}
"""

STORE_NEW_RE = re.compile(r"\bstore\.New\(")
WITH_TX_RE = re.compile(r"\.\s*WithTx\(")
QUERIER_METHOD_RE = re.compile(r"(?m)^\t([A-Z]\w+)\(")


def iter_non_test_go_files():
    for path in sorted(ROOT.rglob("*.go")):
        rel = path.relative_to(ROOT).as_posix()
        if rel.startswith(".tmp/") or rel.startswith("vendor/"):
            continue
        if rel.endswith("_test.go"):
            continue
        yield rel, path


def check_or_sync_scopes(check_only: bool) -> list[str]:
    errors: list[str] = []
    src_bytes = SRC_SCOPES.read_bytes()
    dst_bytes = DST_SCOPES.read_bytes() if DST_SCOPES.exists() else None
    if dst_bytes != src_bytes:
        if check_only:
            errors.append(
                f"{DST_SCOPES.relative_to(ROOT)} differs from {SRC_SCOPES.relative_to(ROOT)}; "
                "run python3 scripts/sqlite/check_store_boundary.py"
            )
        else:
            DST_SCOPES.parent.mkdir(parents=True, exist_ok=True)
            DST_SCOPES.write_bytes(src_bytes)
    return errors


def check_querier_coverage() -> tuple[int, list[str]]:
    errors: list[str] = []
    methods = QUERIER_METHOD_RE.findall(QUERIER_GO.read_text())
    scopes = json.loads(DST_SCOPES.read_text())["scopes"]
    missing = [m for m in methods if m not in scopes]
    if missing:
        errors.append(
            f"internal/db/isolation/method_scopes.json missing {len(missing)} store.Querier method(s): "
            + ", ".join(missing[:10])
        )
    return len(methods), errors


def check_or_annotate_store_db_go(check_only: bool) -> list[str]:
    errors: list[str] = []
    text = STORE_DB_GO.read_text()
    required_markers = (
        "Production callers must use db.Queries",
        "SetTxBoundaryHook(",
        "AttachBoundary(",
        "WrapDB(",
        "boundaryHook",
        'panic("store.Queries.WithTx: nil pgx.Tx")',
    )
    missing = [m for m in required_markers if m not in text]
    if missing:
        if check_only:
            errors.append(
                f"{STORE_DB_GO.relative_to(ROOT)} missing post-sqlc boundary guards: {', '.join(missing)}"
            )
        else:
            STORE_DB_GO.write_text(STORE_DB_GO_TEMPLATE)
    return errors


def scan_non_test_pattern(pattern: re.Pattern[str], allowed_file: str) -> tuple[int, list[str]]:
    total = 0
    offenders: list[str] = []
    for rel, path in iter_non_test_go_files():
        for lineno, line in enumerate(path.read_text().splitlines(), start=1):
            code = line.split("//", 1)[0]
            matches = pattern.findall(code)
            if not matches:
                continue
            total += len(matches)
            if rel != allowed_file:
                offenders.append(f"{rel}:{lineno}: {line.strip()}")
    return total, offenders


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    errors: list[str] = []
    errors.extend(check_or_sync_scopes(args.check))
    errors.extend(check_or_annotate_store_db_go(args.check))

    method_count, cov_errors = check_querier_coverage()
    errors.extend(cov_errors)

    new_total, new_offenders = scan_non_test_pattern(STORE_NEW_RE, ALLOWED_STORE_NEW_FILE)
    if new_offenders:
        errors.append(
            f"found {len(new_offenders)} forbidden non-test store.New( call(s) outside {ALLOWED_STORE_NEW_FILE}:\n  "
            + "\n  ".join(new_offenders[:20])
        )
    if new_total != 1:
        errors.append(
            f"expected non-test store.New( total == 1 (only {ALLOWED_STORE_NEW_FILE}), got {new_total}"
        )

    tx_total, tx_offenders = scan_non_test_pattern(WITH_TX_RE, ALLOWED_WITH_TX_FILE)
    if tx_offenders:
        errors.append(
            f"found {len(tx_offenders)} forbidden non-test .WithTx( call(s) outside {ALLOWED_WITH_TX_FILE}:\n  "
            + "\n  ".join(tx_offenders[:20])
        )
    if tx_total != 1:
        errors.append(
            f"expected non-test .WithTx( total == 1 (only {ALLOWED_WITH_TX_FILE}), got {tx_total}"
        )

    if errors:
        for err in errors:
            print(f"store-boundary error: {err}", file=sys.stderr)
        return 1

    print(
        f"store boundary ok (non-test store.New( = {new_total}, only in {ALLOWED_STORE_NEW_FILE}; "
        f"non-test .WithTx( = {tx_total}, only in {ALLOWED_WITH_TX_FILE}; "
        f"Querier methods covered = {method_count}; internal/db/isolation/method_scopes.json in sync)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
